"""Build the rover mission's terrain files from NASA Moon Trek (LRO LOLA) tiles.

Downloads WMTS tiles for the Shackleton crater rim (lunar south pole), crops them to
the "Site04: Shackleton Rim" box, and writes:
  missions/rover/data/terrain.js       48x48 grid: slope class, elevation, hillshade
  missions/rover/assets/hillshade.png  background map picture
  missions/rover/assets/slope.png      colour slope picture

Run from the repo root:  python scripts/build_terrain.py
Needs: Python 3.10+, Pillow (pip install pillow).

"""
import io
import json
import subprocess
import urllib.request
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT_DATA = ROOT / "missions" / "rover" / "data" / "terrain.js"
OUT_ASSETS = ROOT / "missions" / "rover" / "assets"

# Moon Trek south polar stereographic tile grid (from each layer's WMTSCapabilities.xml)
ORIGIN = 1095930.0          # top-left corner is (-ORIGIN, +ORIGIN) metres
ZOOM = 9
TILE_M = 2191860.0 / 2 ** ZOOM  # metres covered by one 256 px tile at this zoom
BOX = (-9000.0, -15235.0, 7000.0, 1000.0)  # Site04 Shackleton Rim: xmin, ymin, xmax, ymax
N = 48                       # game grid is N x N cells (about 333 m per cell)

BASE = "https://trek.nasa.gov/tiles/Moon/SP/{layer}/1.0.0/default/default028mm/{z}/{r}/{c}.png"
LAYERS = {
    "below10": "ColorSlope_10below_LRO_LOLA_DEM_SPole875_5m",
    "below15": "ColorSlope_15below_LRO_LOLA_DEM_SPole875_5m",
    "above20": "ColorSlope_20above_LRO_LOLA_DEM_SPole875_5m",
    "slope": "ColorSlope_LRO_LOLA_DEM_SPole875_5mp_v04",
    "gray": "LRO_LOLA_Gray_SPole875_5mp_v04",
    "shade": "Site04_final_adj_5mpp_Hillshade",
}


def get(url: str) -> bytes:
    try:
        with urllib.request.urlopen(url, timeout=30) as resp:
            return resp.read()
    except Exception:
        # Windows curl uses the system certificate store, which helps behind some antivirus proxies.
        return subprocess.run(["curl.exe", "-sf", url], check=True, capture_output=True).stdout


def mosaic(layer: str) -> Image.Image:
    xmin, ymin, xmax, ymax = BOX
    c0, c1 = int((xmin + ORIGIN) // TILE_M), int((xmax + ORIGIN) // TILE_M)
    r0, r1 = int((ORIGIN - ymax) // TILE_M), int((ORIGIN - ymin) // TILE_M)
    img = Image.new("RGBA", ((c1 - c0 + 1) * 256, (r1 - r0 + 1) * 256))
    for r in range(r0, r1 + 1):
        for c in range(c0, c1 + 1):
            tile = Image.open(io.BytesIO(get(BASE.format(layer=layer, z=ZOOM, r=r, c=c)))).convert("RGBA")
            img.paste(tile, ((c - c0) * 256, (r - r0) * 256))
    px = 256 / TILE_M
    left = (xmin + ORIGIN - c0 * TILE_M) * px
    top = (ORIGIN - ymax - r0 * TILE_M) * px
    return img.crop((round(left), round(top), round(left + (xmax - xmin) * px), round(top + (ymax - ymin) * px)))


def cell_mean(img: Image.Image, i: int, j: int, fn) -> float:
    w, h = img.size
    box = img.crop((i * w // N, j * h // N, (i + 1) * w // N, (j + 1) * h // N))
    pixels = box.get_flattened_data() if hasattr(box, "get_flattened_data") else box.getdata()
    vals = [fn(p) for p in pixels]
    return sum(vals) / len(vals)


def main() -> None:
    imgs = {k: mosaic(v) for k, v in LAYERS.items()}
    opaque = lambda p: 1.0 if p[3] > 128 else 0.0
    slope, elev, shade = [], [], []
    for j in range(N):
        for i in range(N):
            if cell_mean(imgs["below10"], i, j, opaque) > 0.5:
                s = 0  # under 10 degrees
            elif cell_mean(imgs["below15"], i, j, opaque) > 0.5:
                s = 1  # 10 to 15 degrees
            elif cell_mean(imgs["above20"], i, j, opaque) > 0.5:
                s = 3  # over 20 degrees
            else:
                s = 2  # 15 to 20 degrees
            slope.append(s)
            elev.append(round(cell_mean(imgs["gray"], i, j, lambda p: p[0])))
            shade.append(round(cell_mean(imgs["shade"], i, j, lambda p: p[0])))

    OUT_DATA.parent.mkdir(parents=True, exist_ok=True)
    OUT_ASSETS.mkdir(parents=True, exist_ok=True)
    meta = {
        "source": "NASA Moon Trek WMTS, LRO LOLA 87.5S DEM products (5 m/px) and Site04 Shackleton Rim hillshade",
        "layers": LAYERS,
        "box_m": BOX,
        "cell_m": round((BOX[2] - BOX[0]) / N),
        "slopeClasses": ["<10 deg", "10-15 deg", "15-20 deg", ">20 deg"],
        "elevNote": "elev is the 0-255 grey level of the LOLA DEM picture (relative height, higher = brighter)",
    }
    grid = {"n": N, "meta": meta, "slope": "".join(map(str, slope)), "elev": elev, "shade": shade}
    OUT_DATA.write_text(
        "// Generated by scripts/build_terrain.py from NASA Moon Trek data. Do not edit by hand.\n"
        f"export const TERRAIN = {json.dumps(grid, separators=(',', ':'))};\n",
        encoding="utf-8",
    )
    size = (480, 480)
    imgs["shade"].convert("L").resize(size, Image.LANCZOS).save(OUT_ASSETS / "hillshade.png", optimize=True)
    imgs["slope"].convert("RGB").resize(size, Image.LANCZOS).save(OUT_ASSETS / "slope.png", optimize=True)
    counts = [slope.count(k) for k in range(4)]
    print(f"Wrote {OUT_DATA.relative_to(ROOT)}; slope class counts {counts}; elev {min(elev)}-{max(elev)}")


if __name__ == "__main__":
    main()
